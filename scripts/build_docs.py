"""Build the two combined documents (Markdown, PDF, Word) from their sources.

    python scripts/build_docs.py

Sources: docs/business/Business-Description.md and docs/technical/00-08 (06 is
generated by scripts/data_dictionary.py). Mermaid blocks become the rendered
PNGs in docs/diagrams/ (the PDF renderer clips tall Mermaid drawings; images
always fit the page). PDF and Word come from gstack's make-pdf.
"""
from __future__ import annotations

import re
import struct
import subprocess
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parents[1] / "docs"
MAKE_PDF = Path.home() / ".claude/skills/gstack/make-pdf/dist/pdf"
DIAGRAMS = {
    "The business process, end to end": "01-business-process.png",
    "One scheduled run": "02-etl-end-to-end.png",
    "ETL end to end": "02-etl-end-to-end.png",
    "Discovery and extraction": "03-extract.png",
    "Transformation rules": "04-transform.png",
    "Loading one wave": "05-load.png",
    "Data model (core relationships)": "06-data-model.png",
    "Data sources and where they land": "07-data-sources.png",
    "The 12-week sector rotation and its paired topics": "08-survey-cadence.png",
    "Life of a survey in the pipeline": "archify-survey-lifecycle.png",
}
HEADER = ("**Forsta ETL, data storage and operations for the Consumer Insight Portal.** Version 1.0 · "
          "13 October 2026 · Owner: Data Automation (Coresight Research)\n\nBuilt from the section files in "
          "`docs/technical/` (00–08); the data dictionary is generated from the live database.\n\n")


def fit(png: str) -> str:
    """A width that keeps a tall diagram on one page (6.5 x 8 in usable)."""
    w, h = struct.unpack(">II", (DOCS / "diagrams" / png).read_bytes()[16:24])
    return f"{{width={max(30, min(100, round(100 * 8.0 / 6.5 * w / h)))}%}}" if h > w else ""


def as_images(text: str) -> str:
    def swap(m: re.Match) -> str:
        png = DIAGRAMS.get(m.group(1))
        return f"![{m.group(1)} — flowchart diagram](diagrams/{png}){fit(png)}" if png else m.group(0)
    return re.sub(r'```mermaid title="([^"]+)"\n.*?```', swap, text, flags=re.S)


def main() -> int:
    business = (DOCS / "business/Business-Description.md").read_text()
    business = re.sub(r"\A# .*\n", "**Consumer Insight Portal — Business Description**\n", business)
    technical = HEADER + "\n".join((p.read_text()) for p in sorted((DOCS / "technical").glob("0[0-8]-*.md")))
    outputs = {"CIP-Business-Description": business, "CIP-Technical-Specification": technical}
    for name, text in outputs.items():
        text = as_images(text.replace("(docs/diagrams/", "(diagrams/").replace("../diagrams/", "diagrams/"))
        (DOCS / f"{name}.md").write_text(text)
        title = "CIP — " + name.split("-", 1)[1].replace("-", " ")
        for target, extra in ((f"{name}.pdf", []), (f"{name}.docx", ["--to", "docx"])):
            subprocess.run([str(MAKE_PDF), "generate", "--quiet", "--cover", "--toc", "--no-chapter-breaks",
                            "--author", "Data Automation · Coresight Research", "--title", title,
                            str(DOCS / f"{name}.md"), str(DOCS / target), *extra], check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
